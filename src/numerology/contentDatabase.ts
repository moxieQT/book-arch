/**
 * Синтез детального описания для любой комбинации позиции и Аркана
 */
export function getArcanaPositionContent(positionId: string, arcanaId: number): ArcanaPositionContent {
  const posDef = POSITIONS_REGISTRY[positionId] ?? POSITIONS_REGISTRY.soul
  const arcana = getArcana(arcanaId)
  const pantheon = getPantheonForArcana(arcanaId)

  const curatedKey = `${positionId}_${arcanaId}`
  const curated = CURATED_COMBINATIONS[curatedKey]

  const highFigure = pantheon.highFigures[0] ?? {
    name: arcana.archetypeTitle.split('/')[0].trim(),
    aspect: arcana.lightKey,
  }
  const shadowFigure = pantheon.shadowFigures[0] ?? {
    name: `Теневой ${arcana.name}`,
    aspect: arcana.shadowKey,
  }

  // Генерация смысловых проекций в зависимости от группы позиций
  let defaultEssence = ''
  let defaultTask = ''
  let defaultIntegration = ''

  if (posDef.group === 'core') {
    defaultEssence = `В позиции «${posDef.name}» Аркан ${arcana.roman} (${arcana.name}) проявляется как ${arcana.archetypeTitle}. Это ваш фундамент: ${arcana.shortDesc} Ваша врожденная направленность строится на импульсе: ${arcana.lightKey}`
    defaultTask = `Освоить зрелую октаву ${arcana.name}а, преодолеть автоматические страхи и стать сознательным проводником этой силы в мире.`
    defaultIntegration = `Замечайте моменты, когда вы действуете из силы ${arcana.name}а, а не из страха поражения. Доверяйте своему природному импульсу.`
  } else if (posDef.group === 'shadow') {
    defaultEssence = `В позиции «${posDef.name}» энергия ${arcana.name}а находится в вытесненном или защитном состоянии. Вы можете бессознательно подавлять в себе ${arcana.shadowKey}, боясь показаться уязвимым или разрушительным. Однако именно здесь скрыт резервуар вашей неисчерпаемой мощи.`
    defaultTask = `Не бороться с теневой гранью, а распознать, какую рану она оберегает. Вернуть вытесненный ресурс ${arcana.name}а в сознание.`
    defaultIntegration = `Перестаньте осуждать в себе и других проявления этой силы. Спросите себя: как применить эту энергию для созидания, а не разрушения?`
  } else if (posDef.group === 'integration') {
    defaultEssence = `В позиции «${posDef.name}» ${arcana.roman} ${arcana.name} выступает как великий алхимический мост целостности. Это высшая ступень вашего раскрытия: соединение человеческого опыта и духовного призвания.`
    defaultTask = `Интегрировать противоречия, собрать разрозненные части опыта воедино и проявить зрелое мастерство жизни.`
    defaultIntegration = `Каждый выбор делайте из состояния полноты. Помните: вы — автор своего мифа, и ${arcana.name} ведет вас к преображению.`
  } else {
    // ancestral
    const isMale = posDef.group === 'ancestral_male'
    defaultEssence = `В родовой системе (${isMale ? 'Мужской род' : 'Женский род'}) Аркан ${arcana.name} указывает на ключевой опыт предков: ${arcana.shortDesc} Через поколения передавалась сила: ${arcana.lightKey} Но также накапливалось напряжение: ${arcana.shadowKey}`
    defaultTask = `Завершить родовое повторение сценария ограничений и стать тем, через кого эта ветвь рода получает исцеление и новую норму.`
    defaultIntegration = `С благодарностью примите силу предков, мысленно сказав: «Я беру ваш свет и ресурс, а боль и долги с почтением оставляю вашему опыту. В моей жизни это будет процветанием».`
  }

  return {
    positionId,
    arcanaId,
    aspectName: posDef.name,
    arcanaTitle: `${arcana.roman} · ${arcana.name}`,
    roman: arcana.roman,
    coreEssence: curated?.coreEssence ?? defaultEssence,
    resource: curated?.resource ?? arcana.lightKey,
    shadow: curated?.shadow ?? arcana.shadowKey,
    lifeManifestations: curated?.lifeManifestations ?? {
      relationships: `В контакте с близкими энергия проявляется через потребность в ${arcana.name === 'Маг' ? 'ясности и слове' : 'глубине и доверии'}; опасность впасть в ${arcana.shadowKey.slice(0, 40)}...`,
      careerAndMoney: `В делах и реализации энергия дает способность вести за собой и создавать результат через качества: ${arcana.lightKey.slice(0, 50)}...`,
      bodyAndSelf: `На уровне физики важно беречь ресурс нервной системы и не допускать соматизации невыраженных эмоций.`,
    },
    innerTask: curated?.innerTask ?? defaultTask,
    highArchetype: {
      name: highFigure.name,
      aspect: highFigure.aspect,
    },
    shadowArchetype: {
      name: shadowFigure.name,
      aspect: shadowFigure.aspect,
    },
    reflectionQuestions: curated?.reflectionQuestions ?? [
      `Как энергия Аркана ${arcana.name} прямо сейчас проявляется в моих ключевых выборах?`,
      `В чем я до сих пор сопротивляюсь принятию своего природного дара: «${arcana.lightKey.slice(0, 40)}...»?`,
      `Что изменится в моей жизни, если я прямо сегодня позволю себе проявить эту силу в полную мощь?`,
    ],
    integration: curated?.integration ?? defaultIntegration,
  }
}
